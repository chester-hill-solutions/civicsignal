/** Reproducible local generation only; never reads credentials or calls a provider. */
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { parseManifest } from '../src/ingest/snapshot-format';

export const REFERENCE_INPUTS = [
  { path: 'docs/evidence/2026-10-31/reference-snapshot-manifest.json', bytes: 44627, sha256: '78c979e9a36ecd2215e4c16c9b0ab6df3ad7dfe6f5efe20addf4f471ac3e3e1e' },
  { path: 'docs/evidence/2026-10-31/reference-staging-archive-receipt.json', bytes: 107498, sha256: '149aeb8f303c3e7b07d8ad088974460b8f9c72ec57a20921ab2e83f254157e29' },
] as const;
export const REFERENCE_OUTPUT = 'services/snapshot/qualification-reference-data.ts';
const sha = (bytes: Uint8Array) => createHash('sha256').update(bytes).digest('hex');
export function generateQualificationReference(manifestRaw: Uint8Array, stagingRaw: Uint8Array): string {
  for (const [n, bytes] of [manifestRaw, stagingRaw].entries()) {
    const pin = REFERENCE_INPUTS[n]!;
    if (bytes.length !== pin.bytes || sha(bytes) !== pin.sha256) throw new Error('Qualification reference input differs.');
  }
  const manifest = parseManifest(new TextDecoder().decode(manifestRaw));
  const receipt = JSON.parse(new TextDecoder().decode(stagingRaw)) as { entries: Record<string, { bytes: number; sha256: string }> };
  const intermediate = Object.entries(receipt.entries).filter(([key]) => !key.endsWith('.metadata.json'));
  const entries = [...intermediate.map(([key, pin]) => [key, pin.bytes, pin.sha256] as const),
    ...manifest.rows.parts.map(pin => [pin.key, pin.bytes, pin.sha256!] as const),
    [manifest.index.key, manifest.index.bytes, manifest.index.sha256!] as const,
    [`snapshots/statutes-v2/${manifest.commit}.manifest.json`, manifestRaw.length, sha(manifestRaw)] as const,
  ].sort(([a], [b]) => a < b ? -1 : a > b ? 1 : 0);
  if (entries.length !== 483 || intermediate.length !== 243 || new Set(entries.map(([key]) => key)).size !== 483 ||
    entries.reduce((sum, [, bytes]) => sum + bytes, 0) !== 1152718942 ||
    entries.some(([, bytes, digest]) => !Number.isSafeInteger(bytes) || bytes < 0 || !/^[a-f0-9]{64}$/.test(digest))) throw new Error('Qualification reference inventory differs.');
  return '/** Generated by scripts/generate-snapshot-qualification-reference.ts; qualification entry only. */\n' +
    `export const QUALIFICATION_REFERENCE_PINS = ${JSON.stringify(REFERENCE_INPUTS, null, 2)} as const;\n` +
    `export const QUALIFICATION_REFERENCE = ${JSON.stringify({ revision: { commit: manifest.commit, date: manifest.date }, parser: manifest.parser, rows: manifest.rows.count, payloadBytes: 1152718942 })} as const;\n` +
    'export const QUALIFICATION_PAYLOADS: readonly (readonly [key: string, bytes: number, sha256: string])[] = [\n' +
    entries.map(entry => '  ' + JSON.stringify(entry) + ',').join('\n') + '\n];\n';
}
if (import.meta.main) {
  const generated = generateQualificationReference(...REFERENCE_INPUTS.map(pin => new Uint8Array(readFileSync(resolve(pin.path)))) as [Uint8Array, Uint8Array]);
  if (process.argv.length !== 2) throw new Error('No arguments are accepted.');
  writeFileSync(resolve(REFERENCE_OUTPUT), generated);
}
